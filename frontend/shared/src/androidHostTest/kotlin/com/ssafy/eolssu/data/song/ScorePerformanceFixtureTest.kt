/** Sidecars generated by the actual CAT CLI for the authored 24-tick study, not FE-created output. */
class ScorePerformanceFixtureTest {
    @Test fun danso() = checkFixture("danso", "DANSO")
    @Test fun sogeum() = checkFixture("sogeum", "SOGEUM")
    @Test fun jeongakDaegeum() = checkFixture("jeongak-daegeum", "JEONGAK_DAEGEUM")
    @Test fun sanjoDaegeum() = checkFixture("sanjo-daegeum", "SANJO_DAEGEUM")

    private fun checkFixture(name: String, instrument: String) {
        val bytes = resource("$name.score.json")
        val sourceHash = MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }
        val source = CommonScoreData.decode(bytes.toString(Charsets.UTF_8))
        assertEquals(instrument, source.score.instrument)
        val song = Song("338", source.score.title, SongLevel.Intro, Jangdan(source.music.jangdan, listOf(4), 4, 1),
            60, "", false, null, source.toScore(), scoreVersion = 1)
        val json = resource("$name.performance.json").toString(Charsets.UTF_8)
        val audioHash = Json.parseToJsonElement(json).jsonObject.getValue("audioSha256").jsonPrimitive.content
        val audio = ModelAudio(song.id, 1, "https://example.com/$name.wav", 60, "QUARTER", 29550, 0, "audio/wav", audioHash)
            .withPerformance(json, song, sourceHash)
        val performance = assertNotNull(audio.performance)
        assertEquals(24000.0, song.durationMs())
        assertEquals(29000.0, performance.durationMs)
        assertEquals(28, performance.segments.size)
        assertEquals(listOf("늘임표"), performance.annotations[ScoreUnitKey("c4-j0", 0, 0)])
        val initial = PracticeUiState(song = song, mode = PracticeMode.Model)
        fun state(ms: Long) = initial.withModelAudio(ModelAudioState(ModelAudioStatus.Playing, audio, ms))
        assertEquals(16.5, state(17000).currentTick)
        assertEquals(17.0, state(18000).currentTick)
        assertEquals(18.5, state(19750).currentTick)
        assertEquals(19.5, state(20750).currentTick)
        assertEquals(20.0, state(21000).currentTick)
        assertEquals(20.0, state(25000).currentTick)
        assertTrue(state(25000).progressPercent > state(21000).progressPercent)
        assertEquals(29, state(25000).totalSeconds)
        assertEquals(24.0, state(29550).currentTick)
        assertEquals(29000.0, state(29550).elapsedMs)
        assertEquals(100f, state(29550).progressPercent)
        assertEquals(24, state(25000).copy(mode = PracticeMode.Recording).totalSeconds)
    }

    private fun resource(name: String) = requireNotNull(javaClass.getResourceAsStream("/scores/performance-preview/$name"))
        .use { it.readBytes() }
}
